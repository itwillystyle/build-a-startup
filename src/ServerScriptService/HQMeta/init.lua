--[[ HQMeta: plot-local bounding-box centre (c) and size (s) of every imported HQ
mesh, keyed by mesh name. The children are GENERATED by the Blender scripts
(V1 by blender/hq.py, V2 by blender/hq2.py, Wafers by blender/wafers.py, through
blender/metafile.py), which merge each run into them, so a rebuilt mesh never
needs hand-pasting again. CampusArch.skinHQ reads this.

The three HQ paths (Wafers W_*, Terrafab T_*, Dome D_*) emit the SAME piece names
under different prefixes, so ONE placer builds any of them. Those entries are
PIECE-LOCAL, not plot-local: Wafers.lua places each at its piece's own frame.
43 pieces per path, except that the Terrafab has no PodiumGlass (its base is a
solid service plinth), which Wafers.lua handles by placing the glass only if the
mesh resolves.

A missing entry here is SILENT: template() returns nil, and nil means "build the
primitive fallback instead", which is also what an un-imported kit looks like. So
tests/offline/hqmeta.spec.luau asserts the three kits stay in step. ]]
local t = {}
for _, n in ipairs({ "V1", "V2", "Wafers", "Terrafab", "Dome" }) do
	for k, v in pairs(require(script:WaitForChild(n))) do
		t[k] = v
	end
end
return t
