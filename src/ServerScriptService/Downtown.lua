--[[
	Downtown (v4.0) -- the city at the east end of the valley, rebuilt.

	His note: "the city in the back still looks trash." It was eight grey boxes
	with glass strips, and five of them stood PAST the valley's walkable edge
	(x ~786) on the hillside, over no ground at all. Now the main road ends at a
	roundabout on a paved downtown plaza (x 620-790), inside the valley, and
	the buildings are the Blender set (blender/city2.py), in the HQ's language:

	  THE RESIDENCES   (668, 64)  apartments. Its lobby has a sales desk and the
	                               residents' lift; each owner's unit is a REAL
	                               floor of this tower (Apartments.lua).
	  VALLEY MOTORS    (664, -62) the car dealership (Cars.lua)
	  the spire        (768, 0)   the landmark at the end of the road
	  the stack        (740, 70)
	  the stepped tower(742, -68)

	Everything a player can touch has box collision (the meshes never collide).
	Missing meshes = nothing breaks: the building is simply absent.
]]
local RS = game:GetService("ReplicatedStorage")

local Downtown = {}

-- generated by blender/city2.py (bbox centre relative to the building origin, size)
local META = {
	Dealer_Showroom = { c = Vector3.new(-0.000, 8.300, 5.600), s = Vector3.new(80.000, 22.600, 64.800) },  -- 1836 tris
	Dealer_Showroom_Glass = { c = Vector3.new(-0.000, 7.900, 4.892), s = Vector3.new(71.609, 13.400, 33.824) },  -- 192 tris
	Residences_Tower = { c = Vector3.new(-0.000, 104.000, 2.750), s = Vector3.new(55.000, 214.000, 52.300) },  -- 34032 tris
	Residences_Tower_Glass = { c = Vector3.new(-0.000, 101.100, 0.000), s = Vector3.new(49.609, 199.400, 46.400) },  -- 8256 tris
	Tower_Spire = { c = Vector3.new(-0.000, 110.500, 0.000), s = Vector3.new(39.000, 227.000, 39.000) },  -- 28516 tris
	Tower_Spire_Glass = { c = Vector3.new(-0.000, 91.350, 0.000), s = Vector3.new(33.609, 179.900, 33.609) },  -- 8700 tris
	Tower_Stack = { c = Vector3.new(-0.298, 68.250, 0.272), s = Vector3.new(46.298, 142.500, 38.630) },  -- 22784 tris
